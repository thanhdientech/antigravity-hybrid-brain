"""Rebuild engine/fluent_index.js + assets/emoji/index.json from github.com/microsoft/fluentui-emoji (MIT).

usage: python build_emoji_index.py [--download <dir>]   # --download also caches every 3D PNG for offline renders
Offline renders: set "emoji_dir": "<dir>" in timeline.json (paths inside mirror the repo's assets/ folder).
"""
import concurrent.futures as cf
import json
import os
import sys
import urllib.parse
import urllib.request

SKILL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = "https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/"


def get(u):
    with urllib.request.urlopen(u, timeout=30) as r:
        return r.read()


tree = json.loads(get("https://api.github.com/repos/microsoft/fluentui-emoji/git/trees/main?recursive=1"))["tree"]
png = {}
for t in tree:
    p = t["path"]
    if p.endswith(".png") and "/3D/" in p and (p.count("/") == 3 or "/Default/3D/" in p):
        png[p.split("/")[1].lower()] = p[len("assets/"):]
metas = [t["path"] for t in tree if t["path"].endswith("metadata.json")]
with cf.ThreadPoolExecutor(32) as ex:
    docs = list(ex.map(lambda p: json.loads(get(RAW + urllib.parse.quote(p))), metas))
idx, kw = {}, []
for m in docs:
    p = png.get(m.get("cldr", "").lower())
    if m.get("glyph") and p:
        idx[m["glyph"]] = p
        kw.append({"e": m["glyph"], "name": m["cldr"], "kw": m.get("keywords", []), "group": m.get("group", "")})
open(os.path.join(SKILL, "engine/fluent_index.js"), "w").write(
    "// Fluent 3D emoji paths (microsoft/fluentui-emoji, MIT). Generated by scripts/build_emoji_index.py — do not edit.\n"
    "const FLUENT_INDEX = " + json.dumps(idx, ensure_ascii=False, separators=(",", ":")) + ";\n")
os.makedirs(os.path.join(SKILL, "assets/emoji"), exist_ok=True)
json.dump(sorted(kw, key=lambda x: x["group"]), open(os.path.join(SKILL, "assets/emoji/index.json"), "w"), ensure_ascii=False, separators=(",", ":"))
print(len(idx), "emoji indexed")
if "--download" in sys.argv:
    out = sys.argv[sys.argv.index("--download") + 1]

    def dl(p):
        f = os.path.join(out, p)
        if not os.path.exists(f):
            os.makedirs(os.path.dirname(f), exist_ok=True)
            open(f, "wb").write(get(RAW + "assets/" + urllib.parse.quote(p)))
    with cf.ThreadPoolExecutor(32) as ex:
        list(ex.map(dl, idx.values()))
    print("cached PNGs ->", out)
